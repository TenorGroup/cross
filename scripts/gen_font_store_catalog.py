#!/usr/bin/env python3
"""Write src/FontStoreCatalog.h from the font store manifest the firmware's FONT_MANIFEST_URL names.

    python3 scripts/gen_font_store_catalog.py <fonts.json> [--check]

The store screen shows a font as "Update" without the network by comparing the receipt of the pack on the card
with the size and crc32 this table holds. The manifest URL is fixed per firmware version, so the table is known
at build time. --check exits 1 when the header on disk differs from what the manifest makes.
"""
import json
import sys
from pathlib import Path

OUT = Path(__file__).resolve().parents[1] / 'src' / 'FontStoreCatalog.h'


def render(manifest):
    rows = []
    for family in sorted(manifest['families'], key=lambda f: f['name']):
        files = family['files']
        if len(files) != 1 or not files[0]['name'].endswith('.cpfontpack'):
            raise SystemExit(f"{family['name']}: the store holds one .cpfontpack per family")
        rows.append((family['name'], files[0]['size'], files[0]['crc32']))
    lines = ['#pragma once', '', '#include <cstddef>', '#include <cstdint>', '',
             '// Generated by scripts/gen_font_store_catalog.py from the font store manifest of this version. Do not edit.',
             '// Name, size and crc32 of each pack the store offers: what the receipt of an installed pack is compared with.',
             'namespace fontstore {',
             'struct Pack {',
             '  const char* name;',
             '  uint32_t size;',
             '  uint32_t crc32;',
             '};',
             'inline constexpr Pack PACKS[] = {']
    lines += [f'    {{"{n}", {s}u, {c}u}},' for n, s, c in rows]
    lines += ['};', 'inline constexpr size_t PACK_COUNT = sizeof(PACKS) / sizeof(PACKS[0]);', '}  // namespace fontstore', '']
    return '\n'.join(lines)


if __name__ == '__main__':
    text = render(json.load(open(sys.argv[1])))
    if '--check' in sys.argv:
        sys.exit(0 if OUT.read_text() == text else 1)
    OUT.write_text(text)
    print('wrote', OUT)
