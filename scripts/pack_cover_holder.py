#!/usr/bin/env python3
"""Pack the gray master of the cover placeholder: python3 scripts/pack_cover_holder.py > src/components/CoverHolderMaster.h

scripts/brand-art/cover-holder/cover-holder-gray.png is 8-bit gray, 298x450 (the largest cover frame),
not dithered. It is stored in strips of STRIP_ROWS rows, each its own zlib stream: the firmware inflates
one strip at a time into a buffer under 4 KB, so the X3 never holds the whole image.
"""
import sys
import zlib
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / 'scripts/brand-art/cover-holder/cover-holder-gray.png'
W, H, STRIP_ROWS = 298, 450, 10


def main() -> None:
    gray = np.asarray(Image.open(SOURCE).convert('L'))
    assert gray.shape == (H, W)
    assert STRIP_ROWS * W < 4096
    streams = []
    for y in range(0, H, STRIP_ROWS):
        raw = gray[y:y + STRIP_ROWS].tobytes()
        packed = zlib.compress(raw, 9)
        assert zlib.decompress(packed) == raw
        streams.append(packed)
    ends, total = [], 0
    for s in streams:
        total += len(s)
        ends.append(total)
    out = sys.stdout
    out.write('// Generated by scripts/pack_cover_holder.py. Do not edit by hand.\n')
    out.write('//\n')
    out.write('// Gray master of the cover placeholder (see scripts/brand-art/cover-holder): %dx%d, 8 bit, not dithered,\n' % (W, H))
    out.write('// %d strips of %d rows, each its own zlib stream; %d bytes packed.\n' % (len(streams), STRIP_ROWS, total))
    out.write('#pragma once\n\n#include <cstdint>\n\nnamespace coverholder {\n')
    out.write('// The crc32 of the 8 bit gray: the cache directory of the placeholder is named after it, so a new master never meets old files.\n')
    out.write('inline constexpr uint32_t MASTER_ID = 0x%08x;\n' % zlib.crc32(gray.tobytes()))
    out.write('inline constexpr int WIDTH = %d, HEIGHT = %d, STRIP_ROWS = %d, STRIPS = %d;\n' % (W, H, STRIP_ROWS, len(streams)))
    out.write('// STRIP_END[i] is where strip i ends in STRIPS_DATA; strip 0 starts at 0.\n')
    out.write('inline constexpr uint16_t STRIP_END[STRIPS] = {\n')
    for i in range(0, len(ends), 10):
        out.write('    ' + ', '.join(str(v) for v in ends[i:i + 10]) + ',\n')
    out.write('};\n')
    data = b''.join(streams)
    assert total < 65536
    out.write('inline constexpr uint8_t STRIPS_DATA[] = {\n')
    for i in range(0, len(data), 20):
        out.write('    ' + ', '.join('0x%02x' % b for b in data[i:i + 20]) + ',\n')
    out.write('};\n')
    out.write('static_assert(sizeof(STRIPS_DATA) == %d);\n}  // namespace coverholder\n' % total)


if __name__ == '__main__':
    main()
