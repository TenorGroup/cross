#!/usr/bin/env python3
"""Regenerates lib/GfxRenderer/InlineSymbolBitmaps.h from the 1-bit reference
PNGs in lib/GfxRenderer/symbol-sources/. The Back-arrow, Select-enter and chevron symbols
are drawn as exact bitmaps, not procedurally, so this script is the only place
their pixels come from.

Switching to another drawn variant is a one-line edit below
(ARROW_VARIANT / SELECT_VARIANT) followed by a rerun; only the chosen variant's
pixels are embedded in the generated header, the others are not compiled in.

Usage: python3 scripts/gen_back_arrow.py
"""
import pathlib

REPO = pathlib.Path(__file__).resolve().parents[1]
SOURCE_DIR = REPO / 'lib/GfxRenderer/symbol-sources'
OUTPUT = REPO / 'lib/GfxRenderer/InlineSymbolBitmaps.h'

ARROW_VARIANT = 'B'
SELECT_VARIANT = 'Enter'


def read_bitmap(path):
    """Reads a 1-bit (black/white) PNG without needing Pillow, so this script
    has no dependency beyond the standard library."""
    import struct
    import zlib
    data = path.read_bytes()
    assert data[:8] == b'\x89PNG\r\n\x1a\n', path
    pos = 8
    width = height = bit_depth = color_type = None
    idat = b''
    while pos < len(data):
        length = struct.unpack('>I', data[pos:pos + 4])[0]
        chunk_type = data[pos + 4:pos + 8]
        chunk = data[pos + 8:pos + 8 + length]
        if chunk_type == b'IHDR':
            width, height, bit_depth, color_type = struct.unpack('>IIBB', chunk[:10])
        elif chunk_type == b'IDAT':
            idat += chunk
        elif chunk_type == b'IEND':
            break
        pos += 12 + length
    raw = zlib.decompress(idat)
    # Reference exports use 8-bit grayscale or grayscale+alpha; chevrons use 1-bit grayscale.
    channels = {0: 1, 4: 2}[color_type]
    assert bit_depth == 8 or (bit_depth == 1 and color_type == 0), path
    row_bytes = (width + 7) // 8 if bit_depth == 1 else width * channels
    stride = 1 + row_bytes
    rows = []
    prev = bytes(row_bytes)
    for y in range(height):
        start = y * stride
        filter_type = raw[start]
        line = bytearray(raw[start + 1:start + stride])
        if filter_type == 1:  # Sub
            for i in range(channels, len(line)):
                line[i] = (line[i] + line[i - channels]) & 0xff
        elif filter_type == 2:  # Up
            for i in range(len(line)):
                line[i] = (line[i] + prev[i]) & 0xff
        elif filter_type == 3:  # Average
            for i in range(len(line)):
                a = line[i - channels] if i >= channels else 0
                b = prev[i]
                line[i] = (line[i] + (a + b) // 2) & 0xff
        elif filter_type == 4:  # Paeth
            for i in range(len(line)):
                a = line[i - channels] if i >= channels else 0
                b = prev[i]
                c = prev[i - channels] if i >= channels else 0
                p = a + b - c
                pa, pb, pc = abs(p - a), abs(p - b), abs(p - c)
                pred = a if pa <= pb and pa <= pc else (b if pb <= pc else c)
                line[i] = (line[i] + pred) & 0xff
        elif filter_type != 0:
            raise ValueError(f'unsupported PNG filter {filter_type}')
        prev = bytes(line)
        rows.append(bytes(line))
    bits = []
    for y in range(height):
        row = []
        for x in range(width):
            sample = ((rows[y][x // 8] >> (7 - x % 8)) & 1) * 255 if bit_depth == 1 else rows[y][x * channels]
            row.append(sample < 128)  # black (ink) => True
        bits.append(row)
    return width, height, bits


def shaft_top(bits, column=12):
    """First row of Back's horizontal shaft, read where nothing but the shaft crosses the column."""
    return next(y for y, row in enumerate(bits) if row[column])


def enter_top(bits):
    """Row of Enter's top, counted from Back's top row (so negative). Enter's tail climbs as far above the shaft as
    Back's tail falls below it, measured from the bottom edge of the shaft to Back's bottom row."""
    first = shaft_top(bits)
    last = max(y for y, row in enumerate(bits) if row[12])
    return first - (len(bits) - 1 - last)


def emit_glyph(name, width, height, bits, top=0):
    assert 0 < width <= 32
    lines = [f'constexpr uint32_t k{name}Rows[] = {{']
    for row in bits:
        value = 0
        for x, on in enumerate(row):
            if on:
                value |= 1 << (width - 1 - x)
        lines.append(f'    0x{value:08X},')
    lines.append('};')
    lines.append(f'constexpr Glyph k{name}{{k{name}Rows, {width}, {height}, {top}}};')
    return '\n'.join(lines)


def main():
    arrow14 = read_bitmap(SOURCE_DIR / f'{ARROW_VARIANT}-net14.png')
    arrow18 = read_bitmap(SOURCE_DIR / f'{ARROW_VARIANT}-net18.png')
    select14 = read_bitmap(SOURCE_DIR / f'{SELECT_VARIANT}-net14.png')
    select18 = read_bitmap(SOURCE_DIR / f'{SELECT_VARIANT}-net18.png')

    parts = [
        '#pragma once',
        '#include <cstdint>',
        '// Generated by scripts/gen_back_arrow.py from the reference PNGs',
        f'// (variant {ARROW_VARIANT} for the return arrow, {SELECT_VARIANT} for the Select key).',
        '// Do not hand-edit; rerun the script to change the variant or refresh pixels.',
        'namespace inlineSymbolBitmaps {',
        'struct Glyph {',
        '  const uint32_t* rows;  // one entry per row, bit (width-1-x) set means ink',
        '  int width;',
        '  int height;',
        '  int top;  // first row, counted from the top row of Back; the strip lines glyphs up on Back',
        '};',
        emit_glyph('BackNet14', *arrow14[:2], arrow14[2]),
        emit_glyph('BackNet18', *arrow18[:2], arrow18[2]),
        emit_glyph('SelectNet14', *select14[:2], select14[2], enter_top(arrow14[2])),
        emit_glyph('SelectNet18', *select18[:2], select18[2], enter_top(arrow18[2])),
    ]
    for direction in ('up', 'down', 'left', 'right'):
        for net in (14, 18):
            width, height, bits = read_bitmap(SOURCE_DIR / f'CHEV-{direction}-net{net}.png')
            # Down hangs from the top edge of Back's shaft to Back's bottom row; Up, Left and Right start on Enter's top row.
            back_bits = (arrow14 if net == 14 else arrow18)[2]
            top = shaft_top(back_bits) if direction == 'down' else enter_top(back_bits)
            assert enter_top(back_bits) <= top and top + height <= len(back_bits), direction
            parts.append(emit_glyph(f'{direction.title()}Net{net}', width, height, bits, top))
    from gen_chevron8 import header_parts
    parts.extend(header_parts())
    parts.extend(['}  // namespace inlineSymbolBitmaps', ''])
    OUTPUT.write_text('\n'.join(parts))
    print(f'Wrote {OUTPUT} ({OUTPUT.stat().st_size} bytes)')
    for label, (w, h, _) in (('arrow14', arrow14), ('arrow18', arrow18), ('select14', select14), ('select18', select18)):
        print(f'  {label}: {w}x{h}')


if __name__ == '__main__':
    main()
